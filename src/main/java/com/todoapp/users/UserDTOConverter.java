package com.todoapp.users;

import com.task_management_app.api.model.OrganisationDTO;
import com.task_management_app.api.model.OrganisationDetailsDTO;
import com.task_management_app.api.model.UserDTO;
import com.todoapp.users.repository.OrganisationProjection;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.List;

@Component
@Slf4j
public class UserDTOConverter {
    public User toEntity(UserDTO userDTO) {
        log.info("[UserDTOConverter - toEntity] - converting dto to User obj");
        User newUser = new User();

        newUser.setFirstName(userDTO.getFirstName());
        newUser.setLastName(userDTO.getLastName());
        newUser.setEmail(userDTO.getEmail());
        newUser.setProfilePicture(userDTO.getProfilePicture());
        newUser.setDeleted(false);
        String userName =
                userDTO.getUserName() == null
                 || userDTO.getUserName().isBlank() ?
                 createAutoGeneratedUsername(userDTO.getFirstName(), userDTO.getLastName())
                 : userDTO.getUserName();
        newUser.setUsername(userName);

        return  newUser;
    }

    public UserDTO toDTO(User user) {
        UserDTO userDTO = new UserDTO();
        userDTO.userId(user.getId());
        userDTO.firstName(user.getFirstName());
        userDTO.lastName(user.getLastName());
        userDTO.email(user.getEmail());
        userDTO.profilePicture(user.getProfilePicture());
        userDTO.isDeleted(user.isDeleted());
        userDTO.userName(user.getUsername());

        return userDTO;
    }

    public List<OrganisationDetailsDTO> toDTOList(List<OrganisationProjection>  projections){
        List<OrganisationDetailsDTO> orgDetailsDTOList = new ArrayList<>();
        for(OrganisationProjection projection : projections) {
            OrganisationDetailsDTO dto = new OrganisationDetailsDTO();
            dto.setOrganisationId(projection.getOrganisationId());
            dto.setName(projection.getOrganisationName());
            orgDetailsDTOList.add(dto);
        }
        return orgDetailsDTOList;
    }


    private String createAutoGeneratedUsername(String first, String last){
        String postFixNum =Integer.toString((int)(Math.random() * 11));
        if(first != null && !first.isBlank() && last != null && !last.isBlank()) {
         return first.concat("_").concat(last).concat(postFixNum);
        }
            return "default".concat(postFixNum);
    }
}
