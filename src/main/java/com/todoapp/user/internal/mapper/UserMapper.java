package com.todoapp.user.internal.mapper;

import com.task_management_app.api.model.UserDTO;
import com.todoapp.user.internal.model.User;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.Named;
import org.mapstruct.ReportingPolicy;



@Mapper(componentModel = "spring",
        unmappedTargetPolicy = ReportingPolicy.IGNORE)
public interface UserMapper {


    @Mapping(target = "id", source = "userId")
    @Mapping(target = "deleted", constant = "false")
    @Mapping(target = "username", source = "userDTO", qualifiedByName = "createUserNameIfNull" )
    User toEntity(UserDTO userDTO);


    @Mapping(target = "userId", source = "id")
    @Mapping(target = "userName", source = "username")
    @Mapping(target = "isDeleted", source = "deleted")
    @Mapping(target = "keycloakId", ignore = true)
    UserDTO toDto(User user);

    @Named("createUserNameIfNull")
    default String createUserNameIfNull(UserDTO userDTO) {
        return userDTO.getUserName() == null
                || userDTO.getUserName().isBlank() ?
                createAutoGeneratedUsername(userDTO.getFirstName(), userDTO.getLastName())
                : userDTO.getUserName();
    }

    default String createAutoGeneratedUsername(String first, String last){
        String postFixNum =Integer.toString((int)(Math.random() * 11));
        if(first != null && !first.isBlank() && last != null && !last.isBlank()) {
            return first.concat("_").concat(last).concat(postFixNum);
        }
        return "default".concat(postFixNum);
    }
}



